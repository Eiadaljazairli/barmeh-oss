export function findForbiddenKeyword(text: string): string | null {
  const normalizedText = text.toLowerCase().trim();

  for (const keyword of FORBIDDEN_KEYWORDS) {
    const escapedKeyword = keyword.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(`(^|\\s)${escapedKeyword}($|\\s|[,.!?;])`, 'i');
    if (regex.test(normalizedText)) {
      return keyword;
    }
  }

  return null;
}

export function countForbiddenKeywords(text: string): number {
  const normalizedText = text.toLowerCase().trim();
  let count = 0;

  for (const keyword of FORBIDDEN_KEYWORDS) {
    const escapedKeyword = keyword.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(`(^|\\s)${escapedKeyword}($|\\s|[,.!?;])`, 'gi');
    const matches = normalizedText.match(regex);
    if (matches) {
      count += matches.length;
    }
  }

  return count;
}
